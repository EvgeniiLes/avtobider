"""Минус-слова по нише: чтобы реклама не тратила деньги на тех, кто ищет не услугу, а обучение, вакансию или товар.

Только одиночные слова и только то, что почти наверняка не нужно салону или студии.
"""
COMMON = ["бесплатно", "вакансия", "вакансии", "работа", "резюме", "скачать", "своими", "дома", "обучение", "курсы", "уроки"]

BY_NICHE = [
    (("маникюр", "ногт", "педикюр"), ["набор", "лампа", "материалы", "мастер-класс", "шеллак", "аппарат", "станок"]),
    (("йог", "пилатес", "растяжк"), ["коврик", "видео", "книга", "приложение", "блок", "ремень", "сертификат"]),
    (("барбер", "стриж", "парикмах"), ["машинка", "ножницы", "набор", "материалы", "краска", "мастер-класс"]),
    (("массаж",), ["аппарат", "массажер", "подушка", "видео", "кресло"]),
    (("фитнес", "тренаж", "спорт"), ["программа", "приложение", "скачать", "видео", "купить"]),
    (("кос", "лаз", "эпиляц", "ресниц", "бров"), ["набор", "аппарат", "материалы", "краска", "мастер-класс"]),
]


def negatives_for(kind: str) -> list[str]:
    """Список минус-слов для этой ниши (без повторов, не больше 40)."""
    low = kind.lower()
    words = list(COMMON)
    for keys, extra in BY_NICHE:
        if any(k in low for k in keys):
            words += extra
    seen, result = set(), []
    for w in words:
        if w not in seen:
            seen.add(w)
            result.append(w)
    return result[:40]
