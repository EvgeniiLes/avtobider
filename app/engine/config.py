"""Пороги правил. Начальные значения описаны в docs/algorithms.md."""
from dataclasses import dataclass


@dataclass(frozen=True)
class EngineConfig:
    window_days: int = 14          # за сколько дней смотрим статистику
    lag_days: int = 1              # последние сутки не берём: данные ещё не дошли
    min_clicks: int = 30           # меньше кликов и расхода: «ещё собираем данные»
    min_spend_factor: float = 2.0  # или расход не меньше N цен клиента
    p_good: float = 0.80           # вероятность «окупается» для хорошего объявления
    p_bad: float = 0.20            # и для слабого
    raise_step: float = 0.20       # на сколько повышаем бюджет за шаг
    cooldown_days: int = 2         # после изменения объявление не трогаем
    warmup_days: int = 0           # сколько дней после запуска не трогаем кампанию в целом: стратегию и бюджет (0: сразу)
    early_days: int = 0            # сколько первых дней объявления судим строже: слабым признаём только при сильных данных (0: как обычно)
    early_p_bad: float = 0.05      # в эти дни «не окупается» только при вероятности окупаемости не выше этой
    early_zero_factor: float = 4.0  # или когда обращений нет вовсе, а расход уже не меньше стольких цен обращения
    switch_leads: int = 10         # обращений за неделю, с которых кампанию переводим на «Максимум конверсий»
    reserve: float = 0.10          # часть недельного бюджета, которую не раздаём
    block_growth_at: float = 0.90  # при таком расходе недели рост запрещён
    ab_min_clicks: int = 100       # кликов на каждый вариант для вердикта
    ab_max_days: int = 14          # тест не длиннее
    ab_confidence: float = 0.95    # уверенность для победителя
    cohort_days: int = 3           # объявления, запущенные вместе каждое в своей кампании: через столько дней сравниваем их друг с другом
    cohort_max_days: int = 7       # не набралась уверенность: через столько дней оставляем лучшее по цифрам в любом случае
    cohort_min_clicks: int = 30    # кликов на каждое объявление, меньше которых судить рано
    cohort_confidence: float = 0.90   # уверенность, с которой слабое объявление уходит раньше срока (мягче, чем у сравнения текстов: решаем за три дня)
    samples: int = 4000            # размер выборки для расчёта вероятностей


# Яндекс сам подбирает ставки и учится на данных: изменения настроек кампании не чаще раза в неделю и не больше чем на 10%
# (справка Директа), поэтому для настоящего Директа правила мягче, чем в примере данных. Слабое объявление можно остановить и раньше:
# на малом бюджете в первые дни у объявления 5-6 кликов в день, и слабым его делает только очень убедительная картина (early_*).
DIRECT_CONFIG = EngineConfig(raise_step=0.10, cooldown_days=7, warmup_days=7, early_days=14, ab_max_days=7)   # сравнение текстов идёт около недели
