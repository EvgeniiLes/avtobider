def catalog_text() -> str:
    """Список референсов для стратега: номер, ниша, приём."""
    return "\n".join(f"{n}: [{NICHES[niche]}] {note}" for n, (niche, note) in REFS.items())


def note(ref_id: int | None) -> str:
    return REFS[ref_id][1] if ref_id in REFS else ""


def load(ref_id: int) -> bytes | None:
    """Файл референса (уменьшенная копия) или None, если такого нет."""
    path = DIR / f"{ref_id:02d}.jpg"
    return path.read_bytes() if ref_id in REFS and path.is_file() else None
